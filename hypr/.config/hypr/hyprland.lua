-- ==========================================
-- Phase 3: environment + autostart
-- ==========================================

-- Environment / themes
hl.env("QT_QPA_PLATFORMTHEME", "qt6ct")

hl.env("XCURSOR_THEME", "Bibata-Modern-Classic")
hl.env("XCURSOR_SIZE", "24")

hl.env("HYPRCURSOR_THEME", "Bibata-Modern-Classic")
hl.env("HYPRCURSOR_SIZE", "24")

hl.env("GTK_THEME", "Adwaita:dark")


-- Start programs once when the Hyprland session starts
hl.on("hyprland.start", function()
    -- Notifications
    hl.exec_cmd("bash -lc 'pgrep -x swaync >/dev/null || exec swaync'")

    -- NetworkManager tray
    hl.exec_cmd(
        "bash -lc 'pgrep -x nm-applet >/dev/null || exec nm-applet --indicator'"
    )

    -- Bluetooth tray
    hl.exec_cmd(
        "bash -lc 'pgrep -x blueman-applet >/dev/null || exec blueman-applet'"
    )

    -- Idle / lock handling
    hl.exec_cmd(
        "bash -lc 'pgrep -x hypridle >/dev/null || exec hypridle'"
    )

    -- Cursor
    hl.exec_cmd(
        "hyprctl setcursor Bibata-Modern-Classic 24"
    )

    -- Static wallpaper
    hl.exec_cmd(
        "bash -lc 'pgrep -x hyprpaper >/dev/null || exec hyprpaper'"
    )

    -- USB / SD / external-drive automount
    hl.exec_cmd(
        "bash -lc 'pgrep -x udiskie >/dev/null || exec udiskie --automount --notify --tray'"
    )
end)


