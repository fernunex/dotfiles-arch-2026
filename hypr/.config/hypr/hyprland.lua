    output = "HDMI-A-2",
    mode = "preferred",
    position = "auto-left",
    scale = 1,
})

-- ==========================================
-- Phase 4: core keybinds + workspaces
-- ==========================================

local mod = "SUPER"

-- Applications
hl.bind(mod .. " + Q", hl.dsp.exec_cmd("kitty"))
hl.bind(mod .. " + R", hl.dsp.exec_cmd("fuzzel"))

-- Window controls
hl.bind(mod .. " + C", hl.dsp.window.close())

hl.bind(
    mod .. " + F",
    hl.dsp.window.fullscreen({
        action = "toggle",
        mode = "fullscreen",
    })
)

hl.bind(
    mod .. " + V",
    hl.dsp.window.float({
        action = "toggle",
    })
)

-- Session
hl.bind(
    mod .. " + M",
    hl.dsp.exec_cmd("hyprshutdown")
)

-- Utilities
hl.bind(
    mod .. " + SHIFT + B",
    hl.dsp.exec_cmd("~/.local/bin/toggle-waybar")
)

hl.bind(
    mod .. " + SHIFT + W",
    hl.dsp.exec_cmd("~/.local/bin/toggle-video-wallpaper")
)

hl.bind(
    mod .. " + N",
    hl.dsp.exec_cmd("swaync-client -t")
)

hl.bind(
    mod .. " + L",
    hl.dsp.exec_cmd("hyprlock")
)

-- Move keyboard focus
hl.bind(
    mod .. " + left",
    hl.dsp.focus({ direction = "l" })
)

hl.bind(
    mod .. " + right",
    hl.dsp.focus({ direction = "r" })
)

hl.bind(
    mod .. " + up",
    hl.dsp.focus({ direction = "u" })
)

hl.bind(
    mod .. " + down",
    hl.dsp.focus({ direction = "d" })
)

-- Workspaces 1-5
for i = 1, 9 do
    local workspace = tostring(i)

    -- Switch to workspace
    hl.bind(
        mod .. " + " .. workspace,
        hl.dsp.focus({
            workspace = workspace,
        })
    )

    -- Move active window to workspace and follow it
    hl.bind(
        mod .. " + SHIFT + " .. workspace,
        hl.dsp.window.move({
            workspace = workspace,
            follow = true,
        })
    )
end
